// Bangun seed pengguna dan konstanta dari daftar di server.js.
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = await readFile(path.join(root, 'server.js'), 'utf8');

function grab(name) {
  const re = new RegExp('const ' + name + '=(\\[[\\s\\S]*?\\]);');
  const m = src.match(re);
  if (!m) throw new Error('Tidak menemukan ' + name + ' di server.js');
  return JSON.parse(m[1]);
}

const kabupaten = grab('KABUPATEN');
const petugas = grab('PETUGAS_SKGB');
const petugasGiling = grab('PETUGAS_GILING');
const hasilPencacahan = grab('HASIL_PENCACAHAN');
const ksaPetakLain = grab('KSA_PETAK_LAIN');
const faseOpsi = grab('FASE_OPSI');
const jenisPemanenan = grab('JENIS_PEMANENAN');

if (kabupaten.length !== 35) throw new Error('Kabupaten harus 35, dapat ' + kabupaten.length);

const users = {};
for (const [kode, nama] of kabupaten) users[kode] = { nama, role: 'kab' };
users['0000'] = { nama: 'Admin Provinsi', role: 'admin' };
users['9999'] = { nama: 'Superadmin', role: 'superadmin' };

const constants = { kabupaten, petugas, petugasGiling, hasilPencacahan, ksaPetakLain, faseOpsi, jenisPemanenan };
const header = '// Generated by scripts/gen-users-seed.mjs from server.js. Do not edit by hand.\n';
const lib = path.join(root, 'functions', 'lib');
await writeFile(path.join(lib, 'users-seed.js'), header + 'export const USERS = ' + JSON.stringify(users, null, 2) + ';\n');
await writeFile(path.join(lib, 'constants.js'), header + 'export const CONSTANTS = ' + JSON.stringify(constants, null, 2) + ';\n');
console.log('seed ok, users=' + Object.keys(users).length);
